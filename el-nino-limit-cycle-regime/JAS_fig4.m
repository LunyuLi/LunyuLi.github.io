%% Dependence of equilibrium on s and sigma
clear
clc

R=1.5;
lam=0.8;
s=0.05:0.001:0.5;
sig=0:0.001:5;

[s1,sig1]=meshgrid(s,sig);
m=lam*R-s1-1;
n=4*s1*(R-1);
x=m+1+sqrt(m.^2+n);

T2eqn=(1-x.^2)./4./s1./R;
qeqn=(x-1)./2./s1;
h1eqn=lam*qeqn;
T1minusT2=qeqn./R;

blueOrangeRed=[0.00,0.00,0.45;...
               0.00,0.18,0.70;...
               0.08,0.36,0.86;...
               0.25,0.52,0.96;...
               0.48,0.73,0.95;...
               0.72,0.90,0.96;...
               1.00,0.93,0.70;...
               0.99,0.72,0.42;...
               0.96,0.46,0.18;...
               0.80,0.20,0.02;...
               0.58,0.04,0.00;...
               0.35,0.00,0.00];

fig=figure('Color','w','Units','pixels','Position',[100,100,1020,640]);
tiledlayout(fig,2,2,'TileSpacing','compact','Padding','compact');

T2clim=[min(T2eqn(:)),max(T2eqn(:))];
drawFilledPanel(nexttile,T2eqn,T2clim,linspace(T2clim(1),T2clim(2),12),...
    '(a) Nondimensional EP SST (T2*)',s1,sig1,blueOrangeRed);

drawFilledPanel(nexttile,T1minusT2,[0.5,3.3],[0.5,0.8,1.0,1.3,1.5,1.8,2.0,2.3,2.6,2.8,3.1,3.3],...
    '(b) Nondimensional SST diff (T1*-T2*)',s1,sig1,blueOrangeRed);

drawFilledPanel(nexttile,qeqn,[0.7,5.0],[0.7,1.1,1.5,1.9,2.3,2.7,3.1,3.5,3.8,4.2,4.6,5.0],...
    '(c) Nondimensional upwelling (q*)',s1,sig1,blueOrangeRed);

drawFilledPanel(nexttile,h1eqn,[0.6,4.0],[0.6,0.9,1.2,1.5,1.8,2.1,2.5,2.8,3.1,3.4,3.7,4.0],...
    '(d) Nondimensional WP thermocline depth (\eta1*)',s1,sig1,blueOrangeRed);

function drawFilledPanel(ax,Z,climRange,cbTicks,titleText,s1,sig1,cmap)
    Zplot=Z;
    Zplot(Zplot<climRange(1))=climRange(1);
    Zplot(Zplot>climRange(2))=climRange(2);

    levels=linspace(climRange(1),climRange(2),size(cmap,1)+1);
    contourf(ax,s1,sig1,Zplot,levels,'LineStyle','none');
    axis(ax,[0.05,0.5,0,5]);
    caxis(ax,climRange);
    colormap(ax,cmap);

    cb=colorbar(ax);
    set(cb,'Ticks',cbTicks,...
        'TickLabels',compose('%.1f',cbTicks),...
        'FontSize',12,...
        'FontName','Times New Roman');

    title(ax,titleText,...
        'Interpreter','tex',...
        'FontName','Times New Roman',...
        'FontSize',13,...
        'FontWeight','bold');
    set(ax,...
        'FontSize',12,...
        'FontName','Times New Roman',...
        'Box','on',...
        'Layer','top',...
        'LineWidth',0.8,...
        'TickDir','in');
    xticks(ax,0.05:0.10:0.45);
    yticks(ax,0:1:5);
    xlabel(ax,'s','FontName','Times New Roman','FontSize',14,'FontAngle','italic');
    ylabel(ax,'\sigma','Interpreter','tex','FontName','Times New Roman','FontSize',14,'FontAngle','italic');
end
